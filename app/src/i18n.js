const STRINGS = { it, de };
export const LANGUAGES = { it: 'Italiano', de: 'Deutsch' };

let language = 'it';

// Lingua del telefono: tedesco se il sistema è in tedesco, altrimenti italiano
export function deviceLanguage() {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale || '';
    return locale.toLowerCase().startsWith('de') ? 'de' : 'it';
  } catch {
    return 'it';
  }
}

export function setLanguage(lang) {
  language = STRINGS[lang] ? lang : 'it';
}

export const getLanguage = () => language;

export function t(key, vars) {
  let s = STRINGS[language][key] ?? it[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

// "1 persona" / "3 persone"
export const persons = (n) => t(n === 1 ? 'common.personOne' : 'common.personMany', { n });

